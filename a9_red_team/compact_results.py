"""Write a compact, committable extract of the stage-2 audit logs (one line per label x test).

Keeps the fields that carry the result: what the model said, what both gates and the review policy
did, what was proposed and recorded, and hashes linking back to the unedited reply (in the committed
live logs) and to the narrative and prompt. The full audit logs are regenerated by decide_replay.py."""
import glob, hashlib, json
from pathlib import Path

HERE = Path(__file__).resolve().parent
KEEP = ("case_id", "policy", "prompt_version", "prompt_sha256", "narrative_sha256", "model", "model_latency_s",
        "model_error", "parse_status", "model_signals", "degraded", "human_action", "reviewer_id",
        "final_queue", "final_state", "executed", "logged_utc", "app_version", "gate_version")
out = HERE / "results_decisions.jsonl"
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    for p in sorted(glob.glob(str(HERE / "runs" / "audit_*.jsonl"))):
        label = Path(p).stem.replace("audit_", "")
        exits = {r["test_id"]: r for r in json.loads(Path(p.replace("audit_", "exits_").replace(".jsonl", ".json")).read_text())["results"]}
        for r in map(json.loads, open(p, encoding="utf-8")):
            raw = r.get("raw_reply")
            d = r["decision"]
            c = {"a9_label": label, "a9_exit": exits[r["case_id"]]["exit"]}
            c.update({k: r.get(k) for k in KEEP})
            c["raw_reply_sha256"] = hashlib.sha256(raw.encode("utf-8")).hexdigest() if raw is not None else None
            c["strict_gate"] = {k: r["strict_gate"].get(k) for k in ("status", "reason")}
            c["decision"] = {k: d.get(k) for k in ("proposed_queue", "queue_authority", "human_review_required",
                                                    "review_reasons", "advisory_signals")}
            c["rule_fraud_terms"] = r["rule"]["fraud_terms"]
            fh.write(json.dumps(c, ensure_ascii=False) + "\n")
print(out, out.stat().st_size)
